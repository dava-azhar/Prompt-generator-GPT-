export function exportAllCommandsJson(commands: SlashCommand[]): void {
  const json = JSON.stringify({
    version: '1.0',
    exportedAt: new Date().toISOString(),
    author: 'HarrisDev Studio',
    totalCommands: commands.length,
    commands,
  }, null, 2);

  const blob = new Blob([json], { type: 'application/json;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = `harrisdev_gpt_commands_backup_${new Date().toISOString().slice(0, 10)}.json`;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

export async function importCommandsFromJsonFile(file: File): Promise<SlashCommand[]> {
  return new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.onload = (event) => {
      try {
        const text = event.target?.result as string;
        const parsed = JSON.parse(text);
        const cmds: SlashCommand[] = Array.isArray(parsed) ? parsed : (parsed.commands || []);
        
        // Validate items
        const valid = cmds.filter(c => c && c.name && c.instructions);
        resolve(valid);
      } catch (err) {
        reject(new Error('Format file JSON tidak valid. Pastikan file backup HarrisDev.'));
      }
    };
    reader.onerror = () => reject(new Error('Gagal membaca file.'));
    reader.readAsText(file);
  });
}
