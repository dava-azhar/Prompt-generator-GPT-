import { SlashCommand } from '../types/command';
import { formatCommandOutput } from './formatter';

export function exportCommandAsTxt(command: SlashCommand): void {
  const content = formatCommandOutput(command);
  const blob = new Blob([content], { type: 'text/plain;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  const fileName = `${command.name.replace(/[^a-zA-Z0-9_-]/g, '_')}_harrisdev.txt`;
  link.download = fileName;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

